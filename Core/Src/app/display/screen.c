void screen_init(u8g2_t *p_u8g2)
{
	if(p_u8g2 == NULL)
	{
		return;
	}

	u8g2 = p_u8g2;
	selected_screen = SCREEN_MAIN;

    u8g2_ClearBuffer(u8g2);
    u8g2_SetBitmapMode(u8g2, 1);
    u8g2_SetFontMode(u8g2, 1);
}

void screen_draw(screen_data_t *data)
{
	if (u8g2 == NULL || data == NULL)
	{
	    return;
	}

    u8g2_ClearBuffer(u8g2);

    switch (selected_screen)
    {
        case SCREEN_MAIN:
            screen_draw_main(data);
            break;

        case SCREEN_DEBUG:
            screen_draw_debug(data);
            break;
    }
}

static void screen_draw_main(screen_data_t *data)
{
	u8g2_SetFont(u8g2, u8g2_font_6x10_tr);

	// top_line
	u8g2_DrawLine(u8g2, 0, 10, 128, 10);
	// top_divider
	u8g2_DrawLine(u8g2, 63, 10, 63, 0);

	// batt_string
	u8g2_DrawStr(u8g2, 2, 8, "Batt:");
	// batt_voltage
	snprintf(message, sizeof(message), "%d.%dV", data->battery_mv / 1000, (data->battery_mv % 1000) / 100);
	u8g2_DrawStr(u8g2, 35, 8, message); //6.0V

	// curr_string
	u8g2_DrawStr(u8g2, 67, 8, "Curr:");
	// current_consmpution_val
	snprintf(message, sizeof(message), "%dmA", data->current_ma);
	u8g2_DrawStr(u8g2, 98, 8, message); //"123mA"


	// joystick_area
	u8g2_DrawEllipse(u8g2, 25, 38, 20, 20, U8G2_DRAW_ALL);
	// joysticks_position
	u8g2_DrawFilledEllipse(u8g2, 25, 38, 2, 2, U8G2_DRAW_ALL);

	// axis
	u8g2_DrawXBM(u8g2, -9, 20, 53, 37, image_axis_bits);
	// throttle_string
	u8g2_DrawStr(u8g2, 44, 22, "Throttle:");
	// throttle_val
	u8g2_DrawStr(u8g2, 98, 22, "-100%");
	// steer_string
	u8g2_DrawStr(u8g2, 62, 32, "Steer:");
	// steer_val
	u8g2_DrawStr(u8g2, 98, 32, "-100%");
	// lights_string
	u8g2_DrawStr(u8g2, 56, 42, "Lights:");
	// lights_val
	u8g2_DrawStr(u8g2, 98, 42, "OFF");
	// message_send_string
	u8g2_DrawStr(u8g2, 58, 61, "TX:");
	// message_send_val
	u8g2_DrawStr(u8g2, 80, 61, "99 msg/s");
}

